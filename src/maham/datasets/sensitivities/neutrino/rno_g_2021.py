import astropy.units as u
import numpy as np
from astropy.table import QTable, Table

from maham._core.metadata import DataSource, DatasetMetadata, ProvenanceType, Reference, StorageMode
from maham.datasets.registry import register_dataset
from maham.datasets.spectra.neutrino.base import NeutrinoSpectrumDataset


_PAPER = Reference(title="Design and Sensitivity of the Radio Neutrino Observatory in Greenland (RNO-G)", authors=("RNO-G Collaboration",), year=2021, doi="10.1088/1748-0221/16/03/P03025", url="https://arxiv.org/abs/2010.12279")
_REPOSITORY = Reference(title="RNO-G public data for Design and Sensitivity of the Radio Neutrino Observatory in Greenland (RNO-G)", authors=("RNO-G Collaboration",), year=2023, url="https://github.com/RNO-G/rno-g_public_data/tree/c7913a3fc3a0a48b0e6689200bf1f4d4e8cf57a0/2010.12279_RNO-G_Design_And_Sensitivity")


@register_dataset
class RNOGDiffuseSensitivity2021(NeutrinoSpectrumDataset):
    metadata = DatasetMetadata(
        id="rno_g.design.diffuse_sensitivity.2021",
        title="RNO-G 35-station five-year diffuse neutrino sensitivity",
        experiment="RNO-G",
        messenger="neutrino",
        data_type="sensitivity",
        description="Derived reproduction of the nominal 2 sigma_noise RNO-G design-study all-flavor differential sensitivity.",
        year=2021,
        confidence_level=0.90,
        quantity="E2phi",
        spectral_kind="differential_intensity",
        energy_unit="GeV",
        value_unit="GeV cm-2 s-1 sr-1",
        flavor_convention="all_flavor",
        solid_angle_convention="per_sr",
        paper=_PAPER,
        dataset_reference=_REPOSITORY,
        source=DataSource(provenance=ProvenanceType.DERIVED, storage=StorageMode.BUNDLED, path="data/datasets/sensitivities/neutrino/rno_g_diffuse_neutrino_sensitivity_2021.csv", sha256="3671911d487aaa8e5186adccde734245e45b92d4a30fde1e918d074bb0ec3dac"),
        notes=(
            "Derived from the official RNO-G Veff_dipole_array_Bastille_secondaries.json at repository commit c7913a3fc3a0a48b0e6689200bf1f4d4e8cf57a0.",
            "Parent effective-volume source SHA256: 8ec29a23489114d39c9163ed94adce4b0ea04fb4e6c135115e0fdd5e0b0df7c6.",
            "Official Figure 24 script SHA256: ca2e905991bf7c6cd2056ff7c09fc5036c112411ab7f54ae5267b77c287ccc90.",
            "Uses nominal 2.00 sigma_noise Veff, CTW 2011 central nu total cross section, ice density 0.917 g/cm3, Feldman-Cousins upper count 2.44, 4pi solid angle, and livetime (2/3)*5 years.",
            "Reproduces Figure 24 mode='approximate', decade_bin='full': the 1/6-decade-grid effective area is multiplied by decade_factor=5 before the differential flux calculation.",
            "The factor 5 is a Figure 24 approximation factor, not a detector station count or generic decade-width conversion.",
            "The source script labels the projection RNO-G 35 stations, 5 years and plots from min_bin=8; MAHAM preserves that displayed support.",
            "The official black uncertainty band is generated by an unseeded Monte Carlo over Veff uncertainty. This bundled curve uses deterministic nominal 2.00 sigma_noise Veff rather than an arbitrary Monte Carlo realization.",
            "No flavor or normalization rescaling is applied in the MAHAM diffuse comparison.",
        ),
        tags=("RNO-G", "neutrino", "sensitivity", "projection", "design study", "derived"),
    )

    def load_raw(self, cache: bool = True, show_progress: bool = True) -> Table:
        return Table.read(self.fetch(cache=cache, show_progress=show_progress), format="ascii.csv")

    def standardize(self, raw: Table) -> QTable:
        unit = u.GeV / (u.cm**2 * u.s * u.sr)
        table = QTable()
        table["energy"] = np.asarray(raw["energy_GeV"], dtype=float) * u.GeV
        table["E2phi"] = np.asarray(raw["E2phi"], dtype=float) * unit
        table.meta["dataset_id"] = self.metadata.id
        table.meta["quantity"] = self.metadata.quantity
        table.meta["flavor_convention"] = self.metadata.flavor_convention
        table.meta["solid_angle_convention"] = self.metadata.solid_angle_convention
        table.meta["confidence_level"] = self.metadata.confidence_level
        table.meta["sensitivity_type"] = "projected_differential_upper_limit"
        table.meta["projection_stations"] = 35
        table.meta["projection_years"] = 5.0
        table.meta["duty_cycle"] = 2.0 / 3.0
        table.meta["feldman_cousins_upper_count"] = 2.44
        table.meta["trigger_threshold_sigma_noise"] = 2.0
        table.meta["cross_section_model"] = "CTW 2011"
        table.meta["ice_density_g_cm3"] = 0.917
        table.meta["figure24_mode"] = "approximate"
        table.meta["figure24_decade_bin"] = "full"
        table.meta["fine_grid_log10_width_decades"] = 1.0 / 6.0
        table.meta["figure24_effective_area_scale_factor"] = 5.0
        table.meta["intended_log10_energy_width_decades"] = 1.0
        table.meta["source_effective_volume_dataset_id"] = "rno_g.design.effective_volume.2021"
        table.meta["source_repository_commit"] = "c7913a3fc3a0a48b0e6689200bf1f4d4e8cf57a0"
        table.meta["provenance"] = self.metadata.source.provenance.value
        return table
